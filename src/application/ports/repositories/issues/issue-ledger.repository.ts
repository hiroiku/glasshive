import type { Observation } from '~/app-kernel/observation.ts';

/* 課題台帳を読むポート。

   ポートが返すのは素材だけである。台帳のパスも errno も外へ出さないし、課題という言葉も
   持たない。テキストをどうパースするかは application の仕事で、実装は在るか・読めたか・
   読めたテキストだけを答える。

   `Observation` を返す。台帳が無いプロジェクトと、台帳を読めなかったプロジェクトは
   別の事実で、どちらも空の一覧になるので、ここで分けておかないと二度と分けられない。
   errno が見えるのは実装の側だけなので、分けられる場所もそこしかない。

   `projectPath` は解決の済んだプロジェクトのパスである。リクエストから来た文字列をそのまま
   渡してはいけない。相対パスを渡すと、開くのは走らせた作業ディレクトリの台帳になり、
   **別のプロジェクトの課題が、尋ねたプロジェクトの課題として返る**。実装はそれを断るが、
   断るのは最後の砦であって、読んでよいパスを決める場所ではない。 */

export interface IssueLedgerRepository {
  /* 台帳ひとつぶんの生のテキスト。一覧も 1 件も、このテキストから起こす。

     台帳が無ければ `absent('no-source')` — bd を使っていないプロジェクトはこうなる。
     観測としては成り立っているので、誤りではない。 */
  readLedgerText(projectPath: string): Promise<Observation<string>>;
}
