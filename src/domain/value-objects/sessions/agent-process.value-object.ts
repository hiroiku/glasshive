/* 生きているプロセスの姿。

   OS から見えるのは pid と作業ディレクトリだけで、どのセッションを回しているかは分からない。
   だから帰属はパスの包含で決め、待機の割り当ては数を合わせる近似で行う。 */

export interface AgentProcess {
  readonly pid: number;
  /* 作業ディレクトリ。解決済みのパスを入れること。

     帰属はプロジェクトの `canonicalPath` と突き合わせる。片方だけが解決されていると、
     パスの書き表し方が揺れている機械で一致しなくなり、**そのプロジェクトの待機が
     残らず終了へ倒れる**。しかもユーザーからは、ただ静かなプロジェクトにしか見えない。

     OS が教える作業ディレクトリ(`lsof -d cwd` や `/proc/<pid>/cwd`)は元から解決済みなので、
     渡す側は普通それをそのまま入れればよい。 */
  readonly cwd: string;
}
