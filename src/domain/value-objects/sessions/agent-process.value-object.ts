/* 生きている道具の姿。

   OS から見えるのは番号と作業場所だけで、どのセッションを回しているかは分からない。
   だから帰属は場所の包含で決め、待機の割り当ては数を合わせる近似で行う。 */

export interface AgentProcess {
  readonly pid: number;
  /* 作業場所。**解決済みの場所を入れること。**

     帰属は巣の `canonicalPath` と突き合わせる。片方だけが解決されていると、
     場所の書き表し方が揺れている機械で一致しなくなり、**その巣の待機が
     残らず終了へ倒れる**。しかも観る人からは、ただ静かな巣にしか見えない。

     OS が教える作業場所(`lsof -d cwd` や `/proc/<pid>/cwd`)は元から解決済みなので、
     渡す側は普通それをそのまま入れればよい。 */
  readonly cwd: string;
}
