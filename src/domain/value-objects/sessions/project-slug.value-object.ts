/* プロジェクトのパスから、`~/.claude/projects` の下に置かれるディレクトリ名を作る。

   英数字でない文字をすべて `-` にするのが Claude Code の決まりである。`/` も `.` も `_` も
   同じ 1 文字になるので、**この名前から元のパスへは戻せない。** 戻す必要も無い —— パスは
   `transcript` の中に書かれていて、そちらが正である。

   ここが在るのは、まだ `transcript` を 1 本も持たないディレクトリを一覧に載せるためである。
   そのディレクトリで Claude Code が動き出した日に同じ名前が作られるので、行は増えも
   改名もせず、セッションだけが増える。 */
export const slugOfPath = (path: string): string => path.replace(/[^a-zA-Z0-9]/g, '-');
